BEGIN;

-- 1. Business profile: supports pre-registration mode.
CREATE TABLE IF NOT EXISTS public.tax_business_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name TEXT NOT NULL DEFAULT 'Gamora Online',
    registration_status TEXT NOT NULL DEFAULT 'pre_registration'
        CHECK (registration_status IN (
            'pre_registration',
            'registered',
            'suspended'
        )),
    registration_number TEXT,
    tin TEXT,
    vat_registered BOOLEAN NOT NULL DEFAULT FALSE,
    vat_number TEXT,
    business_address TEXT,
    country_code TEXT NOT NULL DEFAULT 'TZ',
    currency_code TEXT NOT NULL DEFAULT 'TZS',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Versioned tax rules with evidence and verification status.
CREATE TABLE IF NOT EXISTS public.tax_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name TEXT NOT NULL,
    tax_type TEXT NOT NULL,
    rate NUMERIC(12,6),
    calculation_method TEXT NOT NULL DEFAULT 'manual'
        CHECK (calculation_method IN (
            'manual',
            'percentage',
            'fixed_amount'
        )),
    source_name TEXT,
    source_url TEXT,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    effective_from DATE,
    effective_to DATE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (rate IS NULL OR rate >= 0),
    CHECK (
        effective_to IS NULL
        OR effective_from IS NULL
        OR effective_to >= effective_from
    )
);

-- 3. Obligations are activated only after applicability is verified.
CREATE TABLE IF NOT EXISTS public.tax_obligations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_rule_id BIGINT REFERENCES public.tax_rules(id) ON DELETE RESTRICT,
    obligation_name TEXT NOT NULL,
    tax_type TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'unverified'
        CHECK (status IN (
            'unverified',
            'applicable',
            'not_applicable',
            'under_review'
        )),
    period_type TEXT,
    effective_from DATE,
    effective_to DATE,
    notes TEXT,
    verified_by TEXT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Supplier purchases: records actual procurement costs.
CREATE TABLE IF NOT EXISTS public.supplier_purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_reference TEXT NOT NULL UNIQUE,
    supplier_name TEXT NOT NULL,
    supplier_contact TEXT,
    supplier_tin TEXT,
    order_number TEXT REFERENCES public.orders(order_number)
        ON DELETE SET NULL,
    purchase_date DATE NOT NULL DEFAULT CURRENT_DATE,
    currency_code TEXT NOT NULL DEFAULT 'TZS',
    subtotal NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    other_costs NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (other_costs >= 0),
    discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    payment_status TEXT NOT NULL DEFAULT 'unpaid'
        CHECK (payment_status IN (
            'unpaid',
            'partially_paid',
            'paid'
        )),
    purchase_status TEXT NOT NULL DEFAULT 'recorded'
        CHECK (purchase_status IN (
            'recorded',
            'received',
            'cancelled'
        )),
    receipt_url TEXT,
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Individual items belonging to a supplier purchase.
CREATE TABLE IF NOT EXISTS public.supplier_purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL
        REFERENCES public.supplier_purchases(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    quantity NUMERIC(12,3) NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_cost NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0
        CHECK (discount_amount >= 0),
    line_total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (line_total >= 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Tax return / filing tracker.
CREATE TABLE IF NOT EXISTS public.tax_returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL
        REFERENCES public.tax_obligations(id) ON DELETE RESTRICT,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    due_date DATE,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN (
            'draft',
            'ready_for_review',
            'filed',
            'accepted',
            'rejected',
            'not_required'
        )),
    taxable_amount NUMERIC(14,2),
    estimated_tax NUMERIC(14,2),
    confirmed_tax NUMERIC(14,2),
    filed_at TIMESTAMPTZ,
    reference_number TEXT,
    evidence_url TEXT,
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (period_end >= period_start),
    CHECK (taxable_amount IS NULL OR taxable_amount >= 0),
    CHECK (estimated_tax IS NULL OR estimated_tax >= 0),
    CHECK (confirmed_tax IS NULL OR confirmed_tax >= 0),
    UNIQUE (obligation_id, period_start, period_end)
);

-- 7. Tax payments are separate from customer order payments.
CREATE TABLE IF NOT EXISTS public.tax_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT
        REFERENCES public.tax_obligations(id) ON DELETE RESTRICT,
    tax_return_id BIGINT
        REFERENCES public.tax_returns(id) ON DELETE RESTRICT,
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    payment_method TEXT,
    payment_reference TEXT,
    receipt_number TEXT,
    receipt_url TEXT,
    verification_status TEXT NOT NULL DEFAULT 'unverified'
        CHECK (verification_status IN (
            'unverified',
            'verified',
            'rejected'
        )),
    notes TEXT,
    recorded_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Verified deadlines and reminders.
CREATE TABLE IF NOT EXISTS public.tax_deadlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT
        REFERENCES public.tax_obligations(id) ON DELETE RESTRICT,
    tax_return_id BIGINT
        REFERENCES public.tax_returns(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    due_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'upcoming'
        CHECK (status IN (
            'upcoming',
            'completed',
            'overdue',
            'not_applicable'
        )),
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. Auditable adjustments; no silent changes to tax figures.
CREATE TABLE IF NOT EXISTS public.tax_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_return_id BIGINT
        REFERENCES public.tax_returns(id) ON DELETE RESTRICT,
    adjustment_type TEXT NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    reason TEXT NOT NULL,
    evidence_url TEXT,
    status TEXT NOT NULL DEFAULT 'pending_review'
        CHECK (status IN (
            'pending_review',
            'approved',
            'rejected'
        )),
    created_by TEXT,
    reviewed_by TEXT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for dashboard/report queries.
CREATE INDEX IF NOT EXISTS idx_tax_rules_verified
    ON public.tax_rules (verified, effective_from);

CREATE INDEX IF NOT EXISTS idx_tax_obligations_status
    ON public.tax_obligations (status, tax_type);

CREATE INDEX IF NOT EXISTS idx_supplier_purchases_date
    ON public.supplier_purchases (purchase_date);

CREATE INDEX IF NOT EXISTS idx_supplier_purchases_order
    ON public.supplier_purchases (order_number);

CREATE INDEX IF NOT EXISTS idx_supplier_purchase_items_purchase
    ON public.supplier_purchase_items (purchase_id);

CREATE INDEX IF NOT EXISTS idx_tax_returns_period
    ON public.tax_returns (period_start, period_end);

CREATE INDEX IF NOT EXISTS idx_tax_deadlines_due_date
    ON public.tax_deadlines (due_date, status);

-- Deny direct public/anon/authenticated access.
-- Server-side API routes must authenticate the admin before using
-- the Supabase service-role client. Never expose that key to the browser.
ALTER TABLE public.tax_business_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_obligations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.supplier_purchases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.supplier_purchase_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_returns ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_deadlines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tax_adjustments ENABLE ROW LEVEL SECURITY;

COMMIT;
